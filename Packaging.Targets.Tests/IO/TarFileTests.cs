using Packaging.Targets.IO;
using System;
using System.Collections.Generic;
using System.Formats.Tar;
using System.IO;
using System.IO.Compression;
using System.Text;
using Xunit;

namespace Packaging.Targets.Tests.IO
{
    /// <summary>
    /// Tests the <see cref="TarFileCreator"/> class, and the interoperability of the archives it creates with <see cref="TarReader"/>.
    /// </summary>
    public class TarFileTests
    {
        private const string LongFileName = "./usr/lib/mono/gac/System.Runtime.InteropServices.RuntimeInformation/4.0.0.0__b03f5f7f11d50a3a/System.Runtime.InteropServices.RuntimeInformation.txt";

        /// <summary>
        /// Reads the contents of a <c>.tar</c> file which was extracted from a <c>.deb</c> package.
        /// </summary>
        [Fact]
        public void ReadTarFileTest()
        {
            using (Stream stream = File.OpenRead("Deb/libplist3_1.12-3.1_amd64.deb"))
            using (ArFile arFile = new ArFile(stream, leaveOpen: true))
            {
                // Skip the debian version
                arFile.Read();

                // This is the tar file
                arFile.Read();

                var filenames = new List<string>();

                using (Stream entryStream = arFile.Open())
                using (GZipStream decompressedStream = new GZipStream(entryStream, CompressionMode.Decompress, leaveOpen: true))
                using (TarReader tarReader = new TarReader(decompressedStream, leaveOpen: true))
                {
                    TarEntry entry;
                    while ((entry = tarReader.GetNextEntry()) != null)
                    {
                        filenames.Add(entry.Name);
                    }
                }

                Assert.Contains("./control", filenames);
            }
        }

        /// <summary>
        /// Makes sure archives generated by the previous, hand-written tar writer can be read.
        /// </summary>
        [Fact]
        public void ReadLongFilenameTarFileTest()
        {
            using (Stream stream = File.OpenRead(@"IO/largefilename.tar"))
            using (TarReader reader = new TarReader(stream))
            {
                var names = new List<string>();
                TarEntry entry;
                while ((entry = reader.GetNextEntry()) != null)
                {
                    names.Add(entry.Name);
                }

                Assert.Equal(LongFileName, names[^1]);
            }
        }

        [Fact]
        public void WriteTarWithLongFilenameTest()
        {
            var modified = new DateTimeOffset(2016, 12, 15, 10, 58, 56, TimeSpan.Zero);

            using (Stream output = new MemoryStream())
            {
                using (var writer = TarFileCreator.CreateWriter(output))
                {
                    TarFileCreator.WriteEntry(
                        writer,
                        new ArchiveEntry()
                        {
                            Mode = LinuxFileMode.S_IXOTH | LinuxFileMode.S_IROTH | LinuxFileMode.S_IXGRP | LinuxFileMode.S_IRGRP | LinuxFileMode.S_IXUSR | LinuxFileMode.S_IWUSR | LinuxFileMode.S_IRUSR | LinuxFileMode.S_IFDIR,
                            TargetPath = "./usr/",
                            Group = "root",
                            Owner = "root",
                            Modified = modified,
                        });

                    using (MemoryStream stream = new MemoryStream(Encoding.UTF8.GetBytes("This file has a very long name.")))
                    {
                        TarFileCreator.WriteEntry(
                            writer,
                            new ArchiveEntry()
                            {
                                Mode = (LinuxFileMode)0x81FF,
                                TargetPath = LongFileName,
                                Modified = modified,
                            },
                            stream);
                    }

                    TarFileCreator.WriteEntry(
                        writer,
                        new ArchiveEntry()
                        {
                            Mode = (LinuxFileMode)0xA1FF,
                            TargetPath = "/usr/link",
                            LinkTo = "target",
                            Owner = "root",
                            Group = "root",
                            Modified = modified,
                        });
                }

                output.Position = 0;

                // A tar archive consists of 512-byte blocks.
                Assert.Equal(0, output.Length % 512);

                using (TarReader reader = new TarReader(output))
                {
                    var directory = reader.GetNextEntry();
                    Assert.Equal(TarEntryType.Directory, directory.EntryType);
                    Assert.Equal("./usr/", directory.Name);
                    Assert.Equal("root", ((GnuTarEntry)directory).UserName);
                    Assert.Equal(modified, directory.ModificationTime);
                    Assert.Equal(
                        UnixFileMode.UserRead | UnixFileMode.UserWrite | UnixFileMode.UserExecute |
                        UnixFileMode.GroupRead | UnixFileMode.GroupExecute |
                        UnixFileMode.OtherRead | UnixFileMode.OtherExecute,
                        directory.Mode);

                    var file = reader.GetNextEntry();
                    Assert.Equal(TarEntryType.RegularFile, file.EntryType);
                    Assert.Equal(LongFileName, file.Name);
                    Assert.Equal((UnixFileMode)0x1FF, file.Mode);
                    using (var streamReader = new StreamReader(file.DataStream))
                    {
                        Assert.Equal("This file has a very long name.", streamReader.ReadToEnd());
                    }

                    var link = reader.GetNextEntry();
                    Assert.Equal(TarEntryType.SymbolicLink, link.EntryType);
                    Assert.Equal("./usr/link", link.Name);
                    Assert.Equal("target", link.LinkName);

                    Assert.Null(reader.GetNextEntry());
                }
            }
        }
    }
}
